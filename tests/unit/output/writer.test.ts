import { mkdir, readdir, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import type { GeneratedFile } from '../../../src/codegen/types.ts';
import { MANIFEST_FILENAME, PACKAGE_NAME } from '../../../src/meta.ts';
import {
  applyWrite,
  cleanOutput,
  hashContent,
  isSafeOutputPath,
  planWrite,
  readManifest,
} from '../../../src/output/writer.ts';
import { codes, withTempDir } from '../../helpers.ts';

const MARKER = `// @generated by ${PACKAGE_NAME}\n`;

function files(entries: Record<string, string>): GeneratedFile[] {
  return Object.entries(entries)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([file, content]) => ({ path: file, content: `${MARKER}${content}`, origin: 'test' }));
}

async function write(
  directory: string,
  generated: readonly GeneratedFile[],
  options = { clean: true, force: false },
): Promise<Awaited<ReturnType<typeof applyWrite>>> {
  const planned = await planWrite(generated, directory, options);
  expect(planned.conflicts).toEqual([]);
  return applyWrite(planned);
}

async function kinds(
  directory: string,
  generated: readonly GeneratedFile[],
): Promise<{ changes: Record<string, string>; manifest: string }> {
  const planned = await planWrite(generated, directory, { clean: true, force: false });
  return {
    changes: Object.fromEntries(planned.plan.changes.map((c) => [c.path, c.kind])),
    manifest: planned.manifestChange,
  };
}

/** Names on disk (with their letter case), recursively, as output-relative `/` paths. */
async function names(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { recursive: true, withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) =>
      path.relative(directory, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'),
    )
    .sort();
}

describe('output paths', () => {
  it('accepts only normalized relative paths inside the output directory', () => {
    for (const file of ['client.ts', 'models/pet.ts', 'a/b/c.d.ts', '.hidden/x.ts'])
      expect(isSafeOutputPath(file)).toBe(true);
    for (const file of [
      '',
      '.',
      '..',
      '../x.ts',
      'a/../b.ts',
      './a.ts',
      'models/',
      'a//b.ts',
      '/abs.ts',
      'C:\\x.ts',
      'C:foo.ts',
      'a/b:stream',
      'a\\b.ts',
      'nul\0.ts',
      MANIFEST_FILENAME,
      MANIFEST_FILENAME.toUpperCase(),
    ])
      expect(isSafeOutputPath(file), file).toBe(false);
  });

  it('ignores manifest entries that are not safe file paths', () =>
    withTempDir(async (dir) => {
      const hash = hashContent('x');
      await writeFile(
        path.join(dir, MANIFEST_FILENAME),
        JSON.stringify({
          manifestVersion: 1,
          files: { '.': hash, '..': hash, 'models/': hash, 'C:foo': hash, 'ok.ts': hash },
        }),
      );
      expect(Object.keys((await readManifest(dir))?.files ?? {})).toEqual(['ok.ts']);
      await mkdir(path.join(dir, 'models'));
      // Planning and cleaning neither crash nor touch the directories named by the bad entries.
      expect((await planWrite([], dir, { clean: true, force: true })).conflicts).toEqual([]);
      expect(await cleanOutput(dir, { force: true, dryRun: false })).toMatchObject({ errors: [] });
    }));
});

describe('letter case renames', () => {
  it('keeps files whose name changed only in letter case, on any file system', () =>
    withTempDir(async (dir) => {
      const before = files({
        'index.ts': 'index',
        'models/pet.ts': 'pet',
        'models/category.ts': 'category v1',
        'pet/get-pet.ts': 'get',
      });
      await write(dir, before);
      // `naming.files: 'PascalCase'`: same content under new names, one file also changes.
      const after = files({
        'index.ts': 'index',
        'models/Pet.ts': 'pet',
        'models/Category.ts': 'category v2',
        'Pet/GetPet.ts': 'get',
      });
      const result = await write(dir, after);
      expect(result.deleted).toEqual(['models/category.ts', 'models/pet.ts', 'pet/get-pet.ts']);
      expect(await names(dir)).toEqual([
        MANIFEST_FILENAME,
        'Pet/GetPet.ts',
        'index.ts',
        'models/Category.ts',
        'models/Pet.ts',
      ]);
      expect(await readFile(path.join(dir, 'models/Pet.ts'), 'utf8')).toBe(`${MARKER}pet`);
      expect(await readFile(path.join(dir, 'models/Category.ts'), 'utf8')).toBe(
        `${MARKER}category v2`,
      );
      expect(Object.keys((await readManifest(dir))?.files ?? {})).toEqual([
        'Pet/GetPet.ts',
        'index.ts',
        'models/Category.ts',
        'models/Pet.ts',
      ]);
      // Up to date afterwards.
      expect(await kinds(dir, after)).toEqual({
        changes: {
          'Pet/GetPet.ts': 'unchanged',
          'index.ts': 'unchanged',
          'models/Category.ts': 'unchanged',
          'models/Pet.ts': 'unchanged',
        },
        manifest: 'unchanged',
      });

      // And back.
      await write(dir, before);
      expect(await names(dir)).toEqual([
        MANIFEST_FILENAME,
        'index.ts',
        'models/category.ts',
        'models/pet.ts',
        'pet/get-pet.ts',
      ]);
    }));
});

describe('line endings', () => {
  it('treats generated files checked out with CRLF line endings as unchanged', () =>
    withTempDir(async (dir) => {
      const generated = files({ 'a.ts': 'one\ntwo\n', 'b.ts': 'three\n', 'c.ts': 'four\n' });
      await write(dir, generated);
      for (const file of ['a.ts', 'b.ts', 'c.ts']) {
        const target = path.join(dir, file);
        await writeFile(target, (await readFile(target, 'utf8')).replaceAll('\n', '\r\n'));
      }
      const remaining = generated.filter((file) => file.path !== 'c.ts');
      const planned = await planWrite(remaining, dir, { clean: true, force: false });
      expect(planned.plan.changes.map((c) => [c.path, c.kind])).toEqual([
        ['a.ts', 'unchanged'],
        ['b.ts', 'unchanged'],
        // Not a hand edit: the stale file is deleted rather than kept.
        ['c.ts', 'delete'],
      ]);
      expect(planned.notes).toEqual([]);
      await applyWrite(planned);
      expect(await readFile(path.join(dir, 'a.ts'), 'utf8')).toContain('\r\n');
      expect(await cleanOutput(dir, { force: false, dryRun: false })).toMatchObject({
        deleted: ['a.ts', 'b.ts'],
        kept: [],
      });
    }));
});

describe('file system conflicts', () => {
  it('reports directories and files in the way as conflicts instead of failing', () =>
    withTempDir(async (dir) => {
      await mkdir(path.join(dir, 'client.ts'));
      await writeFile(path.join(dir, 'models'), 'my notes\n');
      const planned = await planWrite(
        files({ 'client.ts': 'client', 'models/pet.ts': 'pet', 'index.ts': 'index' }),
        dir,
        { clean: true, force: true },
      );
      expect(codes(planned.conflicts)).toEqual(['output/user-file', 'output/user-file']);
      expect(planned.conflicts.map((c) => c.message)).toEqual([
        'client.ts cannot be written because client.ts is a directory; nothing was changed.',
        'models/pet.ts cannot be written because models is a file, not a directory; nothing was changed.',
      ]);
    }));

  it('creates no directories outside the output directory', () =>
    withTempDir(async (dir) => {
      const output = path.join(dir, 'gen');
      const outside = path.join(dir, 'outside');
      await mkdir(output);
      await mkdir(outside);
      await symlink(outside, path.join(output, 'extra'), 'dir');
      const planned = await planWrite(files({ 'extra/deep/x.ts': 'x' }), output, {
        clean: true,
        force: false,
      });
      await expect(applyWrite(planned)).rejects.toThrow(/Refusing to write extra\/deep\/x\.ts/);
      expect(await readdir(outside)).toEqual([]);
    }));

  it('checks every file before cleaning and deletes nothing when one is refused', () =>
    withTempDir(async (dir) => {
      const output = path.join(dir, 'gen');
      const outside = path.join(dir, 'outside');
      await write(output, files({ 'client.ts': 'c', 'index.ts': 'i', 'store/order.ts': 'o' }));
      await mkdir(outside);
      await writeFile(path.join(outside, 'order.ts'), `${MARKER}o`);
      await rm(path.join(output, 'store'), { recursive: true });
      await symlink(outside, path.join(output, 'store'), 'dir');
      const result = await cleanOutput(output, { force: false, dryRun: false });
      expect(result.deleted).toEqual([]);
      expect(codes(result.errors)).toEqual(['output/write-failed']);
      expect(result.errors[0]?.message).toContain('Refusing to delete store/order.ts');
      expect((await names(output)).sort()).toEqual([MANIFEST_FILENAME, 'client.ts', 'index.ts']);
      expect(await readdir(outside)).toEqual(['order.ts']);
    }));
});

describe('interrupted runs', () => {
  it('removes temporary files that a process which is gone left behind', () =>
    withTempDir(async (dir) => {
      const generated = files({ 'client.ts': 'c' });
      await write(dir, generated);
      const orphan = 'client.ts.2147483646-0123abcd.tmp';
      const mine = 'notes.txt.2147483646-0123abcd.tmp';
      await writeFile(path.join(dir, orphan), 'partial');
      await writeFile(path.join(dir, mine), 'not ours');
      await write(dir, files({ 'client.ts': 'c2' }));
      const entries = await readdir(dir);
      expect(entries).not.toContain(orphan);
      expect(entries).toContain(mine);
    }));
});
