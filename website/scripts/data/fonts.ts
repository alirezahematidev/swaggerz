/**
 * Metric-adjusted fallback faces (size-adjust, ascent/descent overrides) computed with Capsize,
 * so swapping from the fallback to the web font does not move text.
 */
import { createFontStack } from '@capsizecss/core';
import arial from '@capsizecss/metrics/arial';
import courierNew from '@capsizecss/metrics/courierNew';
import figtree from '@capsizecss/metrics/figtree';
import fraunces from '@capsizecss/metrics/fraunces';
import georgia from '@capsizecss/metrics/georgia';
import splineSansMono from '@capsizecss/metrics/splineSansMono';
import { writeGenerated } from './output.ts';

function fallback(
  primary: Parameters<typeof createFontStack>[0][number],
  local: Parameters<typeof createFontStack>[0][number],
  name: string,
): string {
  const { fontFaces } = createFontStack([primary, local]);
  // Capsize names the face after the primary family ("Figtree Fallback"); the site's stacks use
  // explicit names so the variable web fonts keep their own family names.
  return fontFaces.replace(/font-family: "[^"]+";/, `font-family: "${name}";`);
}

export async function fonts(): Promise<void> {
  const css = [
    '/* Generated by website/scripts/data/fonts.ts from Capsize font metrics. */',
    fallback(figtree, arial, 'Figtree Fallback'),
    fallback(splineSansMono, courierNew, 'Spline Sans Mono Fallback'),
    fallback(fraunces, georgia, 'Fraunces Fallback'),
    '',
  ].join('\n');
  await writeGenerated('fonts.css', css);
}
