import { definePlugin, type GeneratedFile } from 'swaggerz';

export interface OperationCatalogOptions {
  /** Base URL of the API reference; each operation links to `<base>#<operationId>`. */
  readonly docsBaseUrl: string;
}

/**
 * Adds a `@see` link to the reference documentation of every operation and emits `catalog.ts`
 * (or `catalog.js`), a typed list of all operations for building menus, permissions or logs.
 */
export function operationCatalog(options: OperationCatalogOptions) {
  const docsUrl = (operationId: string | undefined, fallback: string) =>
    `${options.docsBaseUrl}#${encodeURIComponent(operationId ?? fallback)}`;

  return definePlugin({
    name: 'operation-catalog',

    jsdoc(block, target) {
      if (target.kind === 'model') return;
      const { operation } = target;
      return {
        ...block,
        tags: [...block.tags, { tag: 'see', text: docsUrl(operation.operationId, operation.key) }],
      };
    },

    generate(ctx): GeneratedFile[] {
      const entries = ctx.project.operations.map((symbol) => ({
        name: symbol.name,
        method: symbol.operation.method.toUpperCase(),
        path: symbol.operation.path,
        summary: symbol.operation.summary ?? '',
        tags: symbol.operation.tags,
        docs: docsUrl(symbol.operation.operationId, symbol.key),
      }));
      // JSON.stringify produces valid, safely escaped JavaScript literals.
      const list = JSON.stringify(entries, null, 2);
      const typescript = ctx.config.output.language === 'typescript';
      const content = typescript
        ? `// @generated by the operation-catalog plugin.\n\nexport const operations = ${list} as const;\n\nexport type OperationName = (typeof operations)[number]['name'];\n`
        : `// @generated by the operation-catalog plugin.\n\n/** @type {const} */\nexport const operations = ${list};\n`;
      return [{ path: typescript ? 'catalog.ts' : 'catalog.js', content, origin: '' }];
    },
  });
}
